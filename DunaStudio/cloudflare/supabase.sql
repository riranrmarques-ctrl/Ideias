-- Usada pelo Worker quando o admin libera o Studio para um e-mail que já tem conta no Supabase
create or replace function studio_find_user_id(p_email text) returns uuid
language sql security definer set search_path = public, auth as $$
  select id from auth.users where lower(email) = lower(p_email) limit 1
$$;
revoke all on function studio_find_user_id(text) from public, anon, authenticated;
grant execute on function studio_find_user_id(text) to service_role;
